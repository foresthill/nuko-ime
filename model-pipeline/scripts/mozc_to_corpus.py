#!/usr/bin/env python3
"""Mozc OSS 辞書 (dictionary_oss/dictionaryNN.txt) から漢字語彙を抽出して corpus 形式で出力する。

## 目的 (Gemini レビュー B / claudedocs/2026-11-22-mozc-integration-eval.md)

nuko-ime (libakaza) は UniDic 3.1.1 + SudachiDict + IPADIC コーパスをベースに辞書を作るが、
自前の小規模コーパスでは拾いきれない日常語・固有名詞・熟語の「語彙穴」が残る。Mozc の OSS 辞書は
約100万語の精緻な語彙を **BSD-3-Clause** で公開しており、MIT/Apache の nuko に組み込みやすい。

本スクリプトは Mozc 辞書から **表層に漢字を含むエントリ** を抽出し、corpus 形式 (`surface/yomi`)
で出力する。make-dict の `--corpus` は make_corpus_dict 経由でフィルタなく全 word を dict に追加
するため、上流 akaza-data / libakaza エンジンに一切手を入れず **語彙ブレンド** できる
(= Mozc 統合 ① のうち「語彙ブレンド」のみ。コスト/品詞接続は akaza アーキに非適用なので採らない)。

## Mozc 辞書フォーマット (タブ区切り 5 列)

```
読み(ひらがな) <TAB> 左品詞ID <TAB> 右品詞ID <TAB> コスト <TAB> 表層
```

- col[0]: 読み (ひらがな)
- col[4]: 表層

品詞 ID (col1/2) とコスト (col3) は使わない (akaza はコストを corpus-stats の unigram trie から
再計算し、品詞接続ラティスを持たないため)。

## 出力フォーマット

sudachi_to_corpus.py と同じ、1 行 1 単語の corpus:

```
愛着/あいちゃく
...
```

## フィルタ方針

- **表層に漢字を含むもののみ** (純カタカナ語・記号・英字は対象外。カタカナ語は別経路や既存辞書で拾える
  うえ、ここで入れると corpus 肥大とノイズを招く。sudachi_to_corpus.py の has_kanji 方針に合わせる)。
- 読みが通常のひらがなで始まること。
- surface/yomi に空白・全角空白・`/` を含むものはフォーマットを壊すのでスキップ。
- (yomi, surface) で重複排除。
"""

import sys
from pathlib import Path

ZENKAKU_SPACE = "　"
HIRAGANA_START = 0x3041
HIRAGANA_END = 0x3094


def has_kanji(s: str) -> bool:
    """文字列に漢字 (CJK Unified Ideographs + Extension A) が含まれるか。"""
    for ch in s:
        cp = ord(ch)
        if (0x4E00 <= cp <= 0x9FFF) or (0x3400 <= cp <= 0x4DBF):
            return True
    return False


def is_hiragana_start(s: str) -> bool:
    """文字列の先頭が通常のひらがな (ぁ〜ゔ) か。"""
    if not s:
        return False
    return HIRAGANA_START <= ord(s[0]) <= HIRAGANA_END


def extract_entries(path: Path, dedupe: set) -> list:
    """1 つの Mozc 辞書ファイルから対象エントリを抽出。重複は dedupe で除去。"""
    entries = []
    with path.open("r", encoding="utf-8") as f:
        for line in f:
            cols = line.rstrip("\n").split("\t")
            if len(cols) < 5:
                continue
            yomi = cols[0]
            surface = cols[4]
            if not yomi or not surface:
                continue
            if not has_kanji(surface):
                continue  # 純カタカナ語・英字・記号は対象外
            if not is_hiragana_start(yomi):
                continue
            if (
                " " in surface
                or " " in yomi
                or ZENKAKU_SPACE in surface
                or ZENKAKU_SPACE in yomi
                or "/" in surface
                or "/" in yomi
            ):
                continue
            key = (yomi, surface)
            if key in dedupe:
                continue
            dedupe.add(key)
            entries.append((surface, yomi))
    return entries


def main():
    if len(sys.argv) < 3:
        print(
            "usage: mozc_to_corpus.py <out_corpus_path> <dictionaryNN.txt> [...]",
            file=sys.stderr,
        )
        sys.exit(2)

    out_path = Path(sys.argv[1])
    dict_paths = [Path(p) for p in sys.argv[2:]]

    dedupe = set()
    all_entries = []
    for p in dict_paths:
        if not p.exists():
            print(f"warning: dict file not found: {p}", file=sys.stderr)
            continue
        es = extract_entries(p, dedupe)
        all_entries.extend(es)
        print(f"  {p.name}: {len(es)} new entries", file=sys.stderr)

    print(f"total: {len(all_entries)} entries", file=sys.stderr)

    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w", encoding="utf-8") as f:
        f.write(";; nuko-ime Mozc OSS 漢字語彙 corpus (BSD-3-Clause, google/mozc)\n")
        f.write(";; Generated by scripts/mozc_to_corpus.py\n")
        f.write(f";; total entries: {len(all_entries)}\n")
        for surface, yomi in all_entries:
            f.write(f"{surface}/{yomi}\n")
    print(f"wrote {out_path}", file=sys.stderr)


if __name__ == "__main__":
    main()
